"""Validate every problem's solution against its tests (real CPython, same tracer as the site) and
write js/data/problems.js. Run: python3 tools/build_problems.py"""
import sys, os, json, glob, re, runpy, importlib
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'problems'))
sys.setrecursionlimit(5000)
import pb
for f in sorted(glob.glob(os.path.join(ROOT, 'tools', 'problems', 'p*.py'))):
    if os.path.basename(f) != 'pb.py':
        importlib.import_module(os.path.basename(f)[:-3])
tr = runpy.run_path(os.path.join(ROOT, 'js', 'engine', 'tracer.py'))

NODE_HDR = {
    'ListNode': '# A ListNode looks like this (it is already made for you):\n# class ListNode:\n#     def __init__(self, val=0, next=None):\n#         self.val = val\n#         self.next = next\n',
    'TreeNode': '# A TreeNode looks like this (it is already made for you):\n# class TreeNode:\n#     def __init__(self, val=0, left=None, right=None):\n#         self.val = val\n#         self.left = left\n#         self.right = right\n',
    'graph': '# A Node looks like this (it is already made for you):\n# class Node:\n#     def __init__(self, val=0, neighbors=None):\n#         self.val = val\n#         self.neighbors = neighbors or []\n',
    'random': '# A Node looks like this (it is already made for you):\n# class Node:\n#     def __init__(self, x, next=None, random=None):\n#         self.val = x\n#         self.next = next\n#         self.random = random\n',
}

def strip_notes(src):
    return '\n'.join(re.sub(r'\s*#>.*$', '', l) for l in src.split('\n'))

def starter(src, mode, fn, kinds):
    out = []
    lines = strip_notes(src).split('\n')
    for l in lines:
        s = l.lstrip()
        ind = len(l) - len(s)
        if s.startswith('class ') and ind == 0:
            out.append(l)
        elif s.startswith('def ') and ind <= 4:
            name = s[4:].split('(')[0]
            if mode == 'design' or name == fn or ind == 0 and name == fn:
                out.append(l)
                out.append(' ' * (ind + 4) + '# ✏️ your code here')
                out.append(' ' * (ind + 4) + 'pass')
                out.append('')
    hdr = ''.join(NODE_HDR[k] for k in sorted(kinds) if k in NODE_HDR)
    return (hdr + '\n' if hdr else '') + '\n'.join(out).rstrip() + '\n'

res, bad = [], 0
slugs = set()
for p in pb.ALL:
    assert p['slug'] not in slugs, p['slug']
    slugs.add(p['slug'])
    sol = p['solution']
    mode = p.get('mode', 'function')
    run = {'code': sol, 'mode': mode}
    if mode == 'function':
        ins = tr['do_inspect']({'code': sol})
        if ins.get('error'):
            print('INSPECT FAIL', p['slug'], ins); bad += 1; continue
        run['fn'] = p.get('fn', ins['fn'])
        run['params'] = [x['name'] for x in ins['params']]
        types = {x['name']: x['type'] for x in ins['params'] if x['type']}
        types.update(p.get('types', {}))
        run['types'] = types
    for k in ('cmp', 'inplace', 'cycle', 'nodeMode'):
        if k in p:
            run[k] = p[k]
    tests = [[list(a), e] for a, e in p['tests']]
    cp = lambda x: json.loads(json.dumps(x))
    out = tr['do_test']({**run, 'tests': cp(tests)})
    fails = [t for t in out['results'] if not t['pass']]
    if out['error'] or fails:
        bad += 1
        print('FAIL', p['slug'], out['error'] or [(t['args'], t.get('got'), t['exp'], t.get('error')) for t in fails][:2])
        continue
    t = tr['do_trace']({**run, 'args': cp(tests[0][0]), 'maxSteps': 3000})
    if t['error'] or t['truncated']:
        print('TRACE WARN', p['slug'], t['error'], t['truncated'])
    item = {k: v for k, v in p.items() if k != 'tests'}
    item.update(run)
    del item['code']
    item['tests'] = tests
    item['steps'] = len(t['steps'])
    item['starter'] = starter(sol, mode, run.get('fn'), set(run.get('types', {}).values()))
    res.append(item)

os.makedirs(os.path.join(ROOT, 'js', 'data'), exist_ok=True)
with open(os.path.join(ROOT, 'js', 'data', 'problems.js'), 'w') as f:
    f.write('/* AUTO-GENERATED by tools/build_problems.py. Edit tools/problems/*.py instead. */\n')
    f.write('export const PROBLEMS = ' + json.dumps(res, ensure_ascii=False, separators=(',', ':')) + ';\n')
by = {}
for p in res:
    by[p['topic']] = by.get(p['topic'], 0) + 1
print(f'{len(res)} ok, {bad} failed', by)
sys.exit(1 if bad else 0)
